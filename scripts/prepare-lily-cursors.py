#!/usr/bin/env python3
"""Convert the supplied 64px ANI theme to lossless browser cursor assets."""
import argparse
import hashlib
import io
import json
import struct
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
DISPLAY_SCALE = 13 / 30
STATES = {
    'normal': ('正常选择', 'auto'),
    'link': ('链接选择', 'pointer'),
    'text': ('文本选择', 'text'),
    'unavailable': ('不可用', 'not-allowed'),
    'help': ('帮助选择', 'help'),
    'progress': ('后台运行', 'progress'),
    'busy': ('忙', 'wait'),
    'crosshair': ('精确选择', 'crosshair'),
    'move': ('移动', 'move'),
    'ns-resize': ('垂直调整大小', 'ns-resize'),
    'ew-resize': ('水平调整大小', 'ew-resize'),
    'nwse-resize': ('沿对角线调整大小 1', 'nwse-resize'),
    'nesw-resize': ('沿对角线调整大小 2', 'nesw-resize'),
    'alternate': ('候选', 'default'),
    'handwriting': ('手写', 'crosshair'),
}


def chunks(data, start=0):
    while start + 8 <= len(data):
        tag, size = struct.unpack_from('<4sI', data, start)
        end = start + 8 + size
        if end > len(data):
            raise ValueError('Truncated ANI chunk')
        yield tag, data[start + 8:end]
        start = end + (size % 2)


def convert(source, output):
    manifest = {'theme': '莉莉概念光标 (64x) Ver1.2', 'displayScale': DISPLAY_SCALE, 'states': {}}
    css = ['/* Generated by scripts/prepare-lily-cursors.py. */',
           '@media (hover:hover) and (pointer:fine){']
    for key, (name, fallback) in STATES.items():
        data = (source / (name + '.ani')).read_bytes()
        if data[:4] != b'RIFF' or data[8:12] != b'ACON':
            raise ValueError('Not an ANI cursor: ' + name)
        parts = dict(chunks(data, 12))
        header = struct.unpack('<9I', parts[b'anih'])
        frames = [d for t, d in chunks(parts[b'LIST'], 4) if t == b'icon']
        sequence = struct.unpack('<' + 'I' * (len(parts[b'seq ']) // 4), parts[b'seq ']) if b'seq ' in parts else range(header[2])
        rates = struct.unpack('<' + 'I' * (len(parts[b'rate']) // 4), parts[b'rate']) if b'rate' in parts else [header[7]] * len(sequence)
        if len(set(rates)) != 1 or len(rates) != len(sequence):
            raise ValueError('This source needs nonuniform frame timing support')
        images, hotspots = [], []
        for index in sequence:
            cur = frames[index]
            entry = struct.unpack_from('<BBBBHHII', cur, 6)
            hotspots.append(entry[4:6])
            image = Image.open(io.BytesIO(cur)).convert('RGBA')
            image.load()
            images.append(image)
        if len(set(hotspots)) != 1 or len(set(i.size for i in images)) != 1:
            raise ValueError('Cursor geometry changes between frames')
        width, height = images[0].size
        sheet = Image.new('RGBA', (width * len(images), height))
        for i, image in enumerate(images):
            sheet.paste(image, (width * i, 0))
        sprite = output / (key + '.webp')
        sheet.save(sprite, 'WEBP', lossless=True, method=6)
        fallback_size = (round(width * DISPLAY_SCALE), round(height * DISPLAY_SCALE))
        images[0].resize(fallback_size, Image.Resampling.LANCZOS).save(output / (key + '.png'), optimize=True)
        digest = hashlib.sha256(sprite.read_bytes()).hexdigest()[:12]
        x, y = hotspots[0]
        manifest['states'][key] = {
            'sprite': '/static/cursors/lily/' + key + '.webp?v=' + digest,
            'width': width, 'height': height, 'hotspotX': x, 'hotspotY': y,
            'frames': len(images), 'durationMs': round(sum(rates) / 60 * 1000, 3),
            'source': name + '.ani', 'sourceSha256': hashlib.sha256(data).hexdigest(),
        }
        if key == 'normal':
            selector = 'body.shrine-site'
        elif key == 'link':
            selector = '.shrine-site :is(a[href],button,summary,[role="button"],input[type="button"],input[type="submit"],input[type="checkbox"],input[type="radio"],label[for])'
        elif key == 'text':
            selector = '.shrine-site :is(textarea,input:not([type="button"]):not([type="submit"]):not([type="checkbox"]):not([type="radio"]):not([type="range"]),[contenteditable="true"])'
        elif key == 'unavailable':
            selector = '.shrine-site :is(:disabled,[aria-disabled="true"])'
        elif key == 'busy':
            selector = '.shrine-site [aria-busy="true"]'
        else:
            selector = '.shrine-site [data-cursor="' + key + '"]'
        fallback_x = round(x * fallback_size[0] / width)
        fallback_y = round(y * fallback_size[1] / height)
        css.append(selector + '{--lily-cursor:' + key + ';cursor:url("/static/cursors/lily/' + key + '.png") ' + str(fallback_x) + ' ' + str(fallback_y) + ',' + fallback + '}')
    css.extend(['}', '.lily-cursor{position:fixed;left:0;top:0;z-index:2147483647;pointer-events:none;user-select:none;background-repeat:no-repeat;contain:strict;will-change:transform;transform-origin:0 0}',
                '.lily-cursor[hidden]{display:none}',
                'html.lily-cursor-on,html.lily-cursor-on *{cursor:none!important}',
                '@keyframes lily-cursor-frames{from{background-position:0 0}to{background-position:var(--lily-strip-end) 0}}',
                '@media print{.lily-cursor{display:none!important}}'])
    (ROOT / 'static/data/lily-cursors.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
    (ROOT / 'static/css/lily-cursor.css').write_text('\n'.join(css) + '\n')
    print('Prepared', len(STATES), 'cursor states; retained original frames, timing and hotspots.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    args = parser.parse_args()
    out = ROOT / 'static/cursors/lily'
    out.mkdir(parents=True, exist_ok=True)
    convert(args.source, out)
